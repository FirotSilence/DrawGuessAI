import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const inventoryPath = join(root, "docs", "third-party-licenses.json");
const noticePath = join(root, "apps", "web", "public", "THIRD_PARTY_NOTICES.txt");
const checkOnly = process.argv.includes("--check");
const packageManagerCli = process.env.npm_execpath;

if (packageManagerCli === undefined || packageManagerCli === "") {
  throw new Error("Run this task through pnpm so the package manager CLI can be resolved.");
}

const licenseResult = spawnSync(
  process.execPath,
  [packageManagerCli, "licenses", "list", "--prod", "--json"],
  { cwd: root, encoding: "utf8", maxBuffer: 16 * 1024 * 1024 }
);
if (licenseResult.status !== 0) {
  throw new Error(licenseResult.stderr || "pnpm licenses list failed");
}

const report = JSON.parse(licenseResult.stdout);
const inventory = JSON.parse(readFileSync(inventoryPath, "utf8"));
// Native helper packages vary by install OS and are not part of the shipped browser/Worker bundles.
const platformPackagePattern =
  /^(?:@esbuild\/.+|@rolldown\/binding-.+|@typescript\/typescript-.+|lightningcss-.+)$/;

function packageKeys(source) {
  return Object.entries(source)
    .flatMap(([license, packages]) =>
      packages
        .filter((record) => !platformPackagePattern.test(record.name))
        .flatMap((record) =>
          record.versions.map((version) => `${record.name}@${version}|${license}`)
        )
    )
    .sort();
}

const liveKeys = packageKeys(report);
const inventoryKeys = packageKeys(inventory);
const missingFromInventory = liveKeys.filter((key) => !inventoryKeys.includes(key));
const missingFromInstall = inventoryKeys.filter((key) => !liveKeys.includes(key));
if (missingFromInventory.length > 0 || missingFromInstall.length > 0) {
  throw new Error(
    [
      "docs/third-party-licenses.json does not match the production dependency graph.",
      ...missingFromInventory.map((key) => `Missing from inventory: ${key}`),
      ...missingFromInstall.map((key) => `Missing from install: ${key}`)
    ].join("\n")
  );
}

function noticeFiles(packagePath) {
  return readdirSync(packagePath, { withFileTypes: true })
    .filter((entry) => entry.isFile() && /^(licen[cs]e|copying|notice)(?:\.|$)/i.test(entry.name))
    .map((entry) => entry.name)
    .sort((left, right) => {
      const rank = (name) => (/^licen[cs]e/i.test(name) ? 0 : /^copying/i.test(name) ? 1 : 2);
      return rank(left) - rank(right) || left.localeCompare(right);
    });
}

const records = Object.entries(report)
  .flatMap(([license, packages]) =>
    packages
      .filter((record) => !platformPackagePattern.test(record.name))
      .map((record) => ({ ...record, license }))
  )
  .sort((left, right) => left.name.localeCompare(right.name));
const inlineNotices = new Map([
  [
    "html-parse-stringify",
    `MIT License

Copyright (c) Henrik Joreteg

Permission is hereby granted, free of charge, to any person obtaining a copy
of this software and associated documentation files (the "Software"), to deal
in the Software without restriction, including without limitation the rights
to use, copy, modify, merge, publish, distribute, sublicense, and/or sell
copies of the Software, and to permit persons to whom the Software is
furnished to do so, subject to the following conditions:

The above copyright notice and this permission notice shall be included in all
copies or substantial portions of the Software.

THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR
IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY,
FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE
AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER
LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM,
OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE
SOFTWARE.`
  ]
]);

const output = [
  "DrawGuessAI Third-Party Notices",
  "",
  "This file contains notices for production dependencies distributed with DrawGuessAI.",
  "It is generated by `pnpm licenses:generate`; do not edit it by hand.",
  "",
  "The DrawGuessAI project itself is licensed under AGPL-3.0-only. The packages below",
  "remain under their own licenses.",
  ""
];

for (const record of records) {
  const seenNotices = new Set();
  output.push("=".repeat(80));
  output.push(`${record.name} ${record.versions.join(", ")}`);
  output.push(`License: ${record.license}`);
  if (record.homepage) output.push(`Homepage: ${record.homepage}`);
  output.push("");
  const packagePath = record.paths[0];
  const files = noticeFiles(packagePath);
  const inlineNotice = inlineNotices.get(record.name);
  if (files.length === 0 && inlineNotice === undefined) {
    throw new Error(`No license or notice text found for ${record.name}`);
  }
  for (const filename of files) {
    const text = readFileSync(join(packagePath, filename), "utf8")
      .replaceAll("\r\n", "\n")
      .split("\n")
      .map((line) => line.trimEnd())
      .join("\n")
      .trim();
    if (seenNotices.has(text)) continue;
    seenNotices.add(text);
    output.push(`--- ${filename} ---`);
    output.push(text);
    output.push("");
  }
  if (inlineNotice !== undefined) {
    output.push("--- MIT license text reconstructed from package metadata ---");
    output.push(inlineNotice);
    output.push("");
  }
}

const expected = `${output.join("\n").trimEnd()}\n`;
if (checkOnly) {
  const actual = readFileSync(noticePath, "utf8").replaceAll("\r\n", "\n");
  if (actual !== expected) {
    throw new Error("THIRD_PARTY_NOTICES.txt is stale; run `pnpm licenses:generate`.");
  }
  process.stdout.write("Third-party notices match the production dependency graph.\n");
} else {
  mkdirSync(dirname(noticePath), { recursive: true });
  writeFileSync(noticePath, expected, "utf8");
  process.stdout.write(`Wrote ${noticePath}\n`);
}
